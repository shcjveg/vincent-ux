import { expect, test } from '@playwright/test'

test('部分成功后只重试失败订单', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 700 })
  await page.goto('/examples/batch/')
  const status = page.getByRole('status')
  await page.getByLabel('新交期').fill('2026-12-20')
  await expect(status).toContainText('PO-101、PO-102')
  await page.getByRole('button', { name: '确认修改 2 笔订单' }).press('Enter')
  const retry = page.getByRole('button', { name: '重试 1 笔失败订单' })
  await expect(retry).toBeEnabled()
  await expect(status).toBeFocused()
  await expect(page.getByLabel('新交期')).toBeDisabled()
  const order = (id: string) => page.getByRole('row', { name: new RegExp(id) })
  await expect(order('PO-101')).toContainText('2026-12-20')
  await expect(order('PO-102')).toContainText('2026-12-03')
  await expect(order('PO-103')).toContainText('2026-12-06')
  await retry.press('Enter')
  await expect(status).toHaveText('正在修改 1 笔订单。')
  await expect(status).toHaveText('全部 2 笔已更新至 2026-12-20。')
  await expect(order('PO-102')).toContainText('2026-12-20')
  await page.getByRole('button', { name: '开始下一批' }).press('Enter')
  await expect(page.getByRole('checkbox', { name: 'PO-101' })).toBeFocused()
  await expect(page.getByRole('button', { name: '确认修改 0 笔订单' })).toBeDisabled()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(320)
})

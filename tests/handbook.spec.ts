import { expect, test } from '@playwright/test'

test('使用方从任务索引核对依据、案例与验收，并能按小节升级旧副本', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/showcase/')
  const directory = page.getByRole('region', { name: '项目使用指南' })
  await directory.getByRole('link', { name: '按任务找设计案例' }).click()
  const task = page.locator('.hb-tasks details').filter({ hasText: '从筛选结果交接一份报表' })
  await task.locator('summary').press('Enter')
  await expect(task).toContainText('下钻后导出，逐条核对地区和城市')
  await task.getByRole('link', { name: '地区明细与导出' }).click()
  await expect(page.locator('#report h2')).toBeInViewport()
  await page.getByRole('link', { name: '验收查询与导出的范围' }).click()
  await expect(page.getByRole('heading', { name: '已应用的查询范围' })).toBeInViewport()
  await page.getByRole('link', { name: '回到刚才的演示' }).click()
  await expect(page.locator('#report h2')).toBeInViewport()
  await directory.getByRole('link', { name: '升级已有副本' }).click()
  await expect(page.getByRole('heading', { name: '升级已有副本' })).toBeInViewport()
  await expect(page.getByRole('article')).toContainText('--dry-run')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
})

test('窄屏可用键盘查目录，版本、当前章节与进入指南前的配色可追溯', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 740 })
  await page.goto('/showcase/?palette=cream-ember')
  const nav = page.getByRole('navigation', { name: '目录', exact: true })
  await expect(nav.locator('[data-version]')).toBeVisible()
  const menu = nav.locator('summary')
  await menu.press('Enter')
  await nav.getByRole('link', { name: '按范围查询与导出' }).press('Enter')
  await expect(nav.locator('details')).not.toHaveAttribute('open', '')
  await expect(page.locator('#report')).toBeFocused()
  await expect(nav.locator('a[href="#report"]')).toHaveAttribute('aria-current', 'location')
  await page.getByRole('link', { name: '验收查询与导出的范围' }).press('Enter')
  await expect(page.locator('html')).toHaveAttribute('data-palette', 'cream-ember')
  await page.getByRole('link', { name: '容器位置稳定原则' }).click()
  await expect(page.getByRole('heading', { name: '视觉原则', exact: true })).toBeAttached()
  await page.getByRole('link', { name: '回到刚才的演示' }).press('Enter')
  await expect(page.locator('#report h2')).toBeInViewport()
  await expect(page.locator('html')).toHaveAttribute('data-palette', 'cream-ember')
})

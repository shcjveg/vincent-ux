import { expect, test } from '@playwright/test'

test('按设计要求查阅验收方法和应用示例，并定位旧副本升级说明', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/showcase/')
  const directory = page.getByRole('region', { name: '项目使用指南' })
  const cases = directory.getByRole('link', { name: '设计要求与验收' })
  await expect(cases).toHaveCSS('text-decoration-line', 'none')
  await cases.click()
  const task = page.locator('.hb-tasks section').filter({ has: page.getByRole('heading', { name: '结果与操作的范围一致', exact: true }) })
  await expect(task).toContainText('核对实际处理的对象与可见范围一致')
  const example = task.getByRole('link', { name: '地区明细与导出' })
  await expect(example).toHaveCSS('text-decoration-line', 'none')
  await example.click()
  await expect(page.locator('#report h2')).toBeInViewport()
  await page.getByRole('link', { name: '查看结果范围规范' }).click()
  await expect(page.getByRole('heading', { name: '已应用的查询范围' })).toBeInViewport()
  await page.getByRole('link', { name: '回到刚才的演示' }).click()
  await expect(page.locator('#report h2')).toBeInViewport()
  await directory.getByRole('link', { name: '升级已有副本' }).click()
  await expect(page.getByRole('heading', { name: '升级已有副本' })).toBeInViewport()
  await expect(page.getByRole('article')).toContainText('--dry-run')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
})

test('窄屏可用键盘查目录，版本、当前章节与进入指南前的配色可追溯', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 740 })
  await page.goto('/showcase/?palette=cream-ember')
  await expect(page.locator('[data-version]')).toBeVisible()
  await expect(page.getByRole('link', { name: '选择组件', exact: true })).toBeVisible()
  const nav = page.getByRole('navigation', { name: '规范示例目录', exact: true })
  await page.getByRole('link', { name: '浏览规范示例目录' }).press('Enter')
  await expect(nav).toBeFocused()
  await expect(nav.getByRole('heading', { level: 3 })).toHaveText(['视觉基础', '组件规范', '页面交互模式'])
  await expect(nav.getByRole('link', { name: '页面交互模式', exact: true })).toHaveCount(0)
  await nav.getByRole('link', { name: '结果与操作的范围一致' }).press('Enter')
  await expect(page.locator('#report')).toBeFocused()
  await expect(nav.locator('a[href="#report"]')).toHaveAttribute('aria-current', 'location')
  await page.getByRole('link', { name: '查看结果范围规范' }).press('Enter')
  await expect(page.locator('html')).toHaveAttribute('data-palette', 'cream-ember')
  await page.getByRole('link', { name: '容器位置稳定原则' }).click()
  await expect(page.getByRole('heading', { name: '视觉原则', exact: true })).toBeAttached()
  await page.getByRole('link', { name: '回到刚才的演示' }).press('Enter')
  await expect(page.locator('#report h2')).toBeInViewport()
  await expect(page.locator('html')).toHaveAttribute('data-palette', 'cream-ember')
})
